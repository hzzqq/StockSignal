def _norm(q: str) -> str:
    return (q or "").strip().lower()


def search(question: str) -> Optional[Dict[str, Any]]:
    """知识库检索：返回 {'entry': 条目, 'score': 得分} 或 None（未命中）。"""
    q = _norm(question)
    if not q:
        return None
    best: Optional[Dict[str, Any]] = None
    for entry in _KB:
        score = 0
        for kw in entry["kw"]:
            if kw.lower() in q:
                # 标题词命中权重更高（更可能是问题主体）
                score += 2 if kw in entry["title"] else 1
        if score <= 0:
            continue
        if best is None or score > best["score"] or (
                score == best["score"] and len(entry["kw"]) > len(best["entry"]["kw"])):
            best = {"entry": entry, "score": score}
    return best


def answer(question: str) -> Optional[str]:
    """知识库问答：命中返回渲染后的 Markdown 解释；未命中返回 None。"""
    hit = search(question)
    if not hit:
        return None
    e = hit["entry"]
    related = [x["title"] for x in _KB if x["cat"] == e["cat"] and x["id"] != e["id"]][:3]
    rel_line = f"\n\n---\n*📚 相关知识：{' · '.join(related)}*（直接问即可）" if related else ""
    return f"### 📘 {e['title']}\n\n{e['content']}{rel_line}"


def stats() -> Dict[str, Any]:
    """知识库自省（供 FastAPI /api/ai/knowledge/stats 与测试）。"""
    cats: Dict[str, int] = {}
    for e in _KB:
        cats[e["cat"]] = cats.get(e["cat"], 0) + 1
    return {"entries": len(_KB), "categories": cats}
